package com.repolens.chunking;

import static org.junit.jupiter.api.Assertions.*;

import org.junit.jupiter.api.Test;

class IndexableFilesTest {

    @Test
    void keepsJavaPomAndApplicationConfig() {
        assertTrue(IndexableFiles.isIndexable("src/main/java/com/demo/UserService.java"));
        assertTrue(IndexableFiles.isIndexable("pom.xml"));
        assertTrue(IndexableFiles.isIndexable("backend/pom.xml"));
        assertTrue(IndexableFiles.isIndexable("src/main/resources/application.yml"));
        assertTrue(IndexableFiles.isIndexable("src/main/resources/application-dev.properties"));
        assertTrue(IndexableFiles.isIndexable("src\\main\\java\\Windows.java"));
    }

    @Test
    void skipsEverythingElse() {
        // build / IDE folders
        assertFalse(IndexableFiles.isIndexable("target/classes/App.java"));
        assertFalse(IndexableFiles.isIndexable("node_modules/x/pom.xml"));
        assertFalse(IndexableFiles.isIndexable(".idea/workspace.xml"));
        // tests
        assertFalse(IndexableFiles.isIndexable("src/test/java/com/demo/Helper.java"));
        assertFalse(IndexableFiles.isIndexable("module/src/test/java/Helper.java"));
        assertFalse(IndexableFiles.isIndexable("src/main/java/UserServiceTest.java"));
        assertFalse(IndexableFiles.isIndexable("src/main/java/UserServiceIT.java"));
        // generated
        assertFalse(IndexableFiles.isIndexable("target/generated-sources/Foo.java"));
        assertFalse(IndexableFiles.isIndexable("src/main/java/generated/Foo.java"));
        // other files
        // docs, SQL and every config file are indexed now (all languages, not just Java)
        assertTrue(IndexableFiles.isIndexable("README.md"));
        assertTrue(IndexableFiles.isIndexable("src/main/resources/data.sql"));
        assertTrue(IndexableFiles.isIndexable("src/main/resources/other.yml"));
        assertFalse(IndexableFiles.isIndexable("src/main/java/com/demo/package-info.java"));
        assertFalse(IndexableFiles.isIndexable(""));
        assertFalse(IndexableFiles.isIndexable(null));
    }

    @Test
    void detectsGeneratedCode() {
        assertTrue(IndexableFiles.looksGenerated("@Generated(value = \"org.mapstruct\")\nclass X {}"));
        assertTrue(IndexableFiles.looksGenerated("// DO NOT EDIT\nclass X {}"));
        assertFalse(IndexableFiles.looksGenerated("class UserService {}"));
    }

    @org.junit.jupiter.api.Test
    void indexesSourceOfEveryLanguageButNotTheirTests() {
        for (String path : new String[] {
            "app/services/auth_service.py",
            "web/src/components/Login.tsx",
            "cmd/server/main.go",
            "src/lib.rs",
            "Api/Controllers/UserController.cs",
            "lib/user.rb",
            "src/App.vue",
            "app/Http/Kernel.php",
            "Sources/App/main.swift",
            "native/core.cpp",
            "scripts/deploy.sh",
            "Dockerfile",
            "package.json",
            "tsconfig.base.json",
            "infra/main.tf",
            "proto/user.proto"
        }) {
            assertTrue(IndexableFiles.isIndexable(path), path);
        }
        for (String path : new String[] {
            "tests/test_auth.py", "app/test_models.py", "web/src/Login.test.tsx", "web/src/api.spec.ts",
            "cmd/server/main_test.go", "spec/user_spec.rb", "web/__tests__/App.tsx", "conftest.py",
            "package-lock.json", "web/dist/app.js", "web/vendor/lib.js", "src/data/countries.json",
            "static/app.min.js", "venv/lib/x.py", "api/__pycache__/m.py", "notes.txt",
            "frontend/src/client/sdk.gen.ts", "proto/user_pb2.py", "api/user.pb.go", "lib/model.g.dart"
        }) {
            assertFalse(IndexableFiles.isIndexable(path), path);
        }
    }

    @org.junit.jupiter.api.Test
    void minifiedOrHugeContentCountsAsGenerated() {
        assertTrue(IndexableFiles.looksGenerated("var a=1;".repeat(2_000)));
        assertTrue(IndexableFiles.looksGenerated("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x"));
        assertTrue(IndexableFiles.looksGenerated("// This file is auto-generated by @hey-api/openapi-ts\nexport {}"));
        assertTrue(IndexableFiles.looksGenerated("x\n".repeat(IndexableFiles.MAX_INDEXED_CHARS)));
        assertFalse(IndexableFiles.looksGenerated("def f():\n    return 1\n".repeat(200)));
    }
}
